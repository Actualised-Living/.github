#!/usr/bin/env python3
"""Split index.html into a ZoneStandard ZS Report template plus its assets.

A ZS report is a database record, not a file: the template below is pasted into
the report editor at /zsreport/edit/, and the large files it needs are uploaded
to attachment storage and listed in `settings.assets`. See
zonestandard/docs/zsreport-assets.md and zsreport-editor.md.

Three things come out of this, into zsreport/:

  template.html          the report template -- paste into the editor
  settings-assets.json   the `settings.assets` array, URLs stubbed
  three-r128-bundle.js   three.js + GLTFLoader, to upload as an attachment

The renderer does not fetch assets or load listed scripts for you, so the
template resolves `zsr.assets` itself and injects the result into the app's
existing PAIN_LOCATOR_ASSET_MAP hook.

The Google Fonts <link> is dropped: a report served from a care-sector portal
should not make every viewer's browser call a third party. Each font stack in
the app already names system fallbacks, so the page just uses those. Pass
--keep-webfonts to leave the link in.

    python3 build/make_zsreport.py [output-dir] [assets-dir] [--keep-webfonts]
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "..", "index.html")

# Root-relative so the report keeps the portal's own access controls; a signed
# blob URL would expire. /form/attachment/view/<directory>/<file>/ redirects to
# a freshly signed blob on each request (webapp/ZS/form/form.py).
STUB = "/form/attachment/view/REPLACE-WITH-ATTACHMENT-DIRECTORY/%s/"
MARKER = "REPLACE-WITH-ATTACHMENT-DIRECTORY"

BUNDLE = "three-r128-bundle.js"

# key -> (filename the app asks assetUrl() for, asset kind, reviewer name)
ASSETS = [
    ("threeBundle", BUNDLE, "script",
     "three.js r128 + GLTFLoader (MIT)",
     "WebGL renderer and the loader that reads the .glb meshes."),
    ("manifest", "manifest.json", "json",
     "Anatomy manifest",
     "Structure names, groups, bounding boxes and landmarks. Read first."),
    ("skin", "skin.glb", "binary",
     "Body surface mesh",
     "The skin shown in the Body surface view."),
    ("muscles", "muscles.glb", "binary",
     "Muscle meshes",
     "339 named muscle structures -- the muscle map, pairs and picking."),
    ("bones", "bones.glb", "binary",
     "Skeleton meshes",
     "Skull, spine, ribs and limb bones."),
    ("nerves", "nerves.glb", "binary",
     "Spinal cord and ganglia",
     "Z-Anatomy spinal dura and dorsal root ganglia (CC BY-SA 4.0)."),
]

HEADER = """{# ===========================================================================
   Body Map -- interactive anatomical reference, as a ZS report.

   Generated by tools/pain-locator/build/make_zsreport.py in the .github repo.
   Edit the app there and regenerate; do not hand-edit this template, or the
   next regeneration will discard the change.

   Requires `settings.assets` to list the six keys below -- see
   settings-assets.json beside this file. The report renders as a whole
   document, so leave "Print button" off: it would nest this inside another
   page. `data` can be an empty object; nothing here reads report data.

   Anatomy: BodyParts3D, (c) The Database Center for Life Science,
   CC BY-SA 2.1 Japan. Spinal cord and ganglia from Z-Anatomy, CC BY-SA 4.0.
   Both are share-alike; confirm the licensing position before publishing.
   =========================================================================== #}
"""

# The renderer hands the template `zsr.assets` and does nothing else with it --
# no fetching, no script tags. tojson is safe under autoescape.
LOADER = """
<script>
/* Resolve settings.assets into the map the app already reads. Keys are stable;
   the filenames are what assetUrl() asks for. */
(function () {
  var listed = {{ zsr.assets|tojson }};
  var byKey = {};
  for (var i = 0; i < listed.length; i++) {
    if (listed[i] && listed[i].key) byKey[listed[i].key] = listed[i].url;
  }
  var FILES = __FILES__;
  var map = {}, missing = [], stubbed = [];
  for (var key in FILES) {
    var url = byKey[key];
    if (!url) { missing.push(key); continue; }
    if (url.indexOf("__MARKER__") >= 0) stubbed.push(key);
    map[FILES[key]] = url;
  }
  window.PAIN_LOCATOR_ASSET_MAP = map;
  window.__BODYMAP_THREE = map["__BUNDLE__"] || null;
  window.__BODYMAP_SETUP = { missing: missing, stubbed: stubbed };
})();
</script>
"""

# The app stashes boot3d() on window.__boot3d when THREE is not yet present, so
# the library can arrive from attachment storage instead of being inlined.
BOOTER = """
<script>
(function () {
  var setup = window.__BODYMAP_SETUP || { missing: [], stubbed: [] };
  function notice(text) {
    var el = document.getElementById("loading");
    var box = document.createElement("div");
    box.setAttribute("role", "status");
    box.style.cssText = "margin:16px;padding:12px 14px;border-radius:8px;"
      + "border:1px solid #c9a227;background:#fdf6e0;color:#5c4708;"
      + "font:14px/1.45 system-ui,sans-serif";
    box.textContent = text;
    if (el && el.parentNode) { el.parentNode.replaceChild(box, el); }
    else { document.body.insertBefore(box, document.body.firstChild); }
  }
  var unset = setup.missing.concat(setup.stubbed);
  if (unset.length) {
    notice("This report is not linked to its anatomy files yet. Upload them to "
      + "attachment storage and replace the placeholder URLs in the report's "
      + "Assets section for: " + unset.join(", ") + ".");
    return;
  }
  var s = document.createElement("script");
  s.src = window.__BODYMAP_THREE;
  s.onload = function () { if (window.__boot3d) window.__boot3d(); };
  s.onerror = function () {
    notice("The 3D library attachment could not be loaded. Check the "
      + "threeBundle asset URL, and that you can open attachments here.");
  };
  document.head.appendChild(s);
})();
</script>
"""


# href on its own line or not; the preconnects go with it.
FONT_LINES = ("<link rel=\"preconnect\" href=\"https://fonts.googleapis.com\">",
              "<link rel=\"preconnect\" href=\"https://fonts.gstatic.com\" crossorigin>")


def drop_webfonts(head):
    """Remove the Google Fonts stylesheet and its preconnects from the head."""
    out, dropped = [], 0
    for line in head.split("\n"):
        t = line.strip()
        if t in FONT_LINES or (t.startswith("<link rel=\"stylesheet\"")
                               and "fonts.googleapis.com" in t):
            dropped += 1
            continue
        out.append(line)
    if dropped != 3:
        sys.exit("expected 3 webfont lines in the head, found %d -- build needs updating"
                 % dropped)
    note = ("<!-- The Google Fonts link is dropped for the report build: a page served\n"
            "     from the portal should not call a third party on every view. The font\n"
            "     stacks below fall back to system faces. -->")
    return "\n".join(out).replace("<style>", note + "\n<style>", 1)


def split_app(text):
    """index.html is three top-level script blocks: three.js, GLTFLoader, app."""
    lines = text.split("\n")
    opens = [i for i, l in enumerate(lines) if l == "<script>"]
    closes = [i for i, l in enumerate(lines) if l == "</script>"]
    if len(opens) != 3 or len(closes) != 3:
        sys.exit("expected exactly 3 top-level script blocks in index.html, "
                 "found %d/%d -- the build needs updating" % (len(opens), len(closes)))
    three = "\n".join(lines[opens[0] + 1:closes[0]])
    gltf = "\n".join(lines[opens[1] + 1:closes[1]])
    app = "\n".join(lines[opens[2] + 1:closes[2]])
    if "THREE" not in three or "GLTFLoader" not in gltf or "boot3d" not in app:
        sys.exit("script blocks are not in the expected order -- build needs updating")
    # Everything before the three.js block, minus its introductory comment.
    head = "\n".join(lines[:opens[0]])
    cut = head.rfind("<!-- three.js r128 (npm")
    if cut < 0:
        sys.exit("three.js comment not found -- the build needs updating")
    head = head[:cut].rstrip() + "\n"
    tail = "\n".join(lines[closes[2] + 1:])
    return head, three, gltf, app, tail


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    keep_fonts = "--keep-webfonts" in sys.argv
    outdir = args[0] if len(args) > 0 else os.path.join(HERE, "..", "zsreport")
    assetdir = args[1] if len(args) > 1 else os.path.join(HERE, "..", "assets")
    os.makedirs(outdir, exist_ok=True)

    head, three, gltf, app, tail = split_app(open(APP, encoding="utf-8").read())
    if not keep_fonts:
        head = drop_webfonts(head)

    bundle = ("/* three.js r128 and its GLTFLoader, concatenated (MIT licence; the\n"
              "   upstream banners follow). Uploaded as a report asset so the report\n"
              "   template stays small enough to edit. */\n" + three + "\n" + gltf + "\n")
    open(os.path.join(outdir, BUNDLE), "w", encoding="utf-8").write(bundle)

    files = {key: name for key, name, _k, _n, _p in ASSETS}
    loader = (LOADER.replace("__FILES__", json.dumps(files))
                    .replace("__MARKER__", MARKER)
                    .replace("__BUNDLE__", BUNDLE))

    # {% raw %} round the app so a future edit containing {{ or {% cannot be
    # eaten by Jinja. The loader block above is deliberately outside it.
    template = (HEADER
                + "{% raw %}\n" + head + "{% endraw %}\n"
                + loader
                + "{% raw %}\n<script>\n" + app + "\n</script>\n{% endraw %}\n"
                + BOOTER
                + "{% raw %}\n" + tail + "{% endraw %}\n")
    open(os.path.join(outdir, "template.html"), "w", encoding="utf-8").write(template)

    man = os.path.join(assetdir, "manifest.json")
    licence = json.load(open(man))["licence"] if os.path.exists(man) else ""
    # nerves are Z-Anatomy, not BodyParts3D -- the manifest's own set metadata
    # says so, and the licences differ.
    versions = {"threeBundle": "three.js r128",
                "nerves": "Z-Anatomy, CC BY-SA 4.0"}
    rows = []
    for key, name, kind, label, purpose in ASSETS:
        size = os.path.join(assetdir, name)
        rows.append({
            "key": key, "name": label, "kind": kind,
            "url": STUB % name,
            "version": versions.get(key, ("BodyParts3D, " + licence) if licence else ""),
            "attachmentRecord": "",
            "purpose": purpose + (" (%.1f MB)" % (os.path.getsize(size) / 1e6)
                                  if os.path.exists(size) else ""),
        })
    open(os.path.join(outdir, "settings-assets.json"), "w", encoding="utf-8").write(
        json.dumps(rows, indent=2) + "\n")

    print("wrote %s/template.html (%.0f KB)"
          % (outdir, os.path.getsize(os.path.join(outdir, "template.html")) / 1e3))
    print("wrote %s/%s (%.0f KB) -- upload as an attachment"
          % (outdir, BUNDLE, os.path.getsize(os.path.join(outdir, BUNDLE)) / 1e3))
    print("wrote %s/settings-assets.json (%d assets, URLs stubbed)" % (outdir, len(rows)))
    print("webfonts: %s" % ("kept (external requests on every view)" if keep_fonts
                            else "dropped, system fallbacks used"))


if __name__ == "__main__":
    main()
